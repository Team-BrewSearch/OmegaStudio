namespace DWSSK.Formats.Video;

internal static class BinkDct
{
    private const int Nw = 512;
    private const int Nc = 2048;

    public static void Inverse(Span<float> a, ReadOnlySpan<float> w)
    {
        int n = a.Length;
        ReadOnlySpan<float> c = w[Nw..];
        DctSub(n, a, c);
        CftFSub(n, a, w);
        RftFSub(n, a, c);
        float xr = a[0] - a[1];
        a[0] += a[1];
        for (int j = 2; j < n; j += 2)
        {
            a[j - 1] = a[j] - a[j + 1];
            a[j] += a[j + 1];
        }
        a[n - 1] = xr;
    }

    private static float Fma(float a, float b, float c) => (float)(((double)a * b) + c);

    private static float Fms(float a, float b, float c) => (float)(((double)a * b) - c);

    private static void DctSub(int n, Span<float> a, ReadOnlySpan<float> c)
    {
        int m = n >> 1;
        int ks = Nc / n;
        int kk = 0;
        for (int j = 1; j < m; j++)
        {
            int k = n - j;
            kk += ks;
            float wkr = c[kk] - c[Nc - kk];
            float wki = c[kk] + c[Nc - kk];
            float xr = Fms(wki, a[j], wkr * a[k]);
            a[j] = Fma(wkr, a[j], wki * a[k]);
            a[k] = xr;
        }
        a[m] *= c[0];
    }

    private static void RftFSub(int n, Span<float> a, ReadOnlySpan<float> c)
    {
        int m = n >> 1;
        int ks = 2 * Nc / m;
        int kk = 0;
        for (int j = 2; j < m; j += 2)
        {
            int k = n - j;
            kk += ks;
            float wkr = 0.5f - c[Nc - kk];
            float wki = c[kk];
            float xr = a[j] - a[k];
            float xi = a[j + 1] + a[k + 1];
            float yr = Fms(wkr, xr, wki * xi);
            float yi = Fma(wkr, xi, wki * xr);
            a[j] -= yr;
            a[j + 1] -= yi;
            a[k] += yr;
            a[k + 1] -= yi;
        }
    }

    private static void CftFSub(int n, Span<float> a, ReadOnlySpan<float> w)
    {
        CftF1st(n, a, w[(Nw - (n >> 2))..]);
        if (n > 512)
        {
            int m = n >> 2;
            for (int q = 0; q < 4; q++)
            {
                bool split = q != 1;
                if (split)
                {
                    CftMdl1(m, a[(q * m)..], w[(Nw - (m >> 1))..]);
                }
                else
                {
                    CftMdl2(m, a[(q * m)..], w[(Nw - m)..]);
                }
                CftLeaf(m, split, a[(q * m)..], w);
            }
        }
        else
        {
            CftLeaf(n, true, a, w);
        }
        BitRv2(n, a);
    }

    private static void BitRv2(int n, Span<float> a)
    {
        int bits = System.Numerics.BitOperations.Log2((uint)n) - 1;
        for (int j = 0; j < n >> 1; j++)
        {
            int k = 0;
            for (int b = 0, v = j; b < bits; b++, v >>= 1)
            {
                k = (k << 1) | (v & 1);
            }
            if (j < k)
            {
                (a[2 * j], a[2 * k]) = (a[2 * k], a[2 * j]);
                (a[(2 * j) + 1], a[(2 * k) + 1]) = (a[(2 * k) + 1], a[(2 * j) + 1]);
            }
        }
    }

    private static void CftLeaf(int n, bool split, Span<float> a, ReadOnlySpan<float> w)
    {
        if (n == 512)
        {
            CftMdl1(128, a, w[(Nw - 64)..]);
            CftF161(a, w[(Nw - 8)..]);
            CftF162(a[32..], w[(Nw - 32)..]);
            CftF161(a[64..], w[(Nw - 8)..]);
            CftF161(a[96..], w[(Nw - 8)..]);
            CftMdl2(128, a[128..], w[(Nw - 128)..]);
            CftF161(a[128..], w[(Nw - 8)..]);
            CftF162(a[160..], w[(Nw - 32)..]);
            CftF161(a[192..], w[(Nw - 8)..]);
            CftF162(a[224..], w[(Nw - 32)..]);
            CftMdl1(128, a[256..], w[(Nw - 64)..]);
            CftF161(a[256..], w[(Nw - 8)..]);
            CftF162(a[288..], w[(Nw - 32)..]);
            CftF161(a[320..], w[(Nw - 8)..]);
            CftF161(a[352..], w[(Nw - 8)..]);
            if (split)
            {
                CftMdl1(128, a[384..], w[(Nw - 64)..]);
                CftF161(a[480..], w[(Nw - 8)..]);
            }
            else
            {
                CftMdl2(128, a[384..], w[(Nw - 128)..]);
                CftF162(a[480..], w[(Nw - 32)..]);
            }
            CftF161(a[384..], w[(Nw - 8)..]);
            CftF162(a[416..], w[(Nw - 32)..]);
            CftF161(a[448..], w[(Nw - 8)..]);
            return;
        }
        CftMdl1(64, a, w[(Nw - 32)..]);
        CftF081(a, w[(Nw - 16)..]);
        CftF082(a[16..], w[(Nw - 16)..]);
        CftF081(a[32..], w[(Nw - 16)..]);
        CftF081(a[48..], w[(Nw - 16)..]);
        CftMdl2(64, a[64..], w[(Nw - 64)..]);
        CftF081(a[64..], w[(Nw - 16)..]);
        CftF082(a[80..], w[(Nw - 16)..]);
        CftF081(a[96..], w[(Nw - 16)..]);
        CftF082(a[112..], w[(Nw - 16)..]);
        CftMdl1(64, a[128..], w[(Nw - 32)..]);
        CftF081(a[128..], w[(Nw - 16)..]);
        CftF082(a[144..], w[(Nw - 16)..]);
        CftF081(a[160..], w[(Nw - 16)..]);
        CftF081(a[176..], w[(Nw - 16)..]);
        if (split)
        {
            CftMdl1(64, a[192..], w[(Nw - 32)..]);
            CftF081(a[240..], w[(Nw - 16)..]);
        }
        else
        {
            CftMdl2(64, a[192..], w[(Nw - 64)..]);
            CftF082(a[240..], w[(Nw - 16)..]);
        }
        CftF081(a[192..], w[(Nw - 16)..]);
        CftF082(a[208..], w[(Nw - 16)..]);
        CftF081(a[224..], w[(Nw - 16)..]);
    }

    private static void CftF1st(int n, Span<float> a, ReadOnlySpan<float> w)
    {
        int mh = n >> 3;
        int m = 2 * mh;
        int j1 = m;
        int j2 = j1 + m;
        int j3 = j2 + m;
        float x0r = a[0] + a[j2];
        float x0i = a[1] + a[j2 + 1];
        float x1r = a[0] - a[j2];
        float x1i = a[1] - a[j2 + 1];
        float x2r = a[j1] + a[j3];
        float x2i = a[j1 + 1] + a[j3 + 1];
        float x3r = a[j1] - a[j3];
        float x3i = a[j1 + 1] - a[j3 + 1];
        a[0] = x0r + x2r;
        a[1] = x0i + x2i;
        a[j1] = x0r - x2r;
        a[j1 + 1] = x0i - x2i;
        a[j2] = x1r - x3i;
        a[j2 + 1] = x1i + x3r;
        a[j3] = x1r + x3i;
        a[j3 + 1] = x1i - x3r;
        float wn4r = w[1];
        float csc1 = w[2];
        float csc3 = w[3];
        float wd1r = 1;
        float wd1i = 0;
        float wd3r = 1;
        float wd3i = 0;
        float wk1r;
        float wk1i;
        float wk3r;
        float wk3i;
        int k = 0;
        for (int j = 2; j < mh - 2; j += 4)
        {
            k += 4;
            wk1r = csc1 * (wd1r + w[k]);
            wk1i = csc1 * (wd1i + w[k + 1]);
            wk3r = csc3 * (wd3r + w[k + 2]);
            wk3i = csc3 * (wd3i - w[k + 3]);
            wd1r = w[k];
            wd1i = w[k + 1];
            wd3r = w[k + 2];
            wd3i = -w[k + 3];
            j1 = j + m;
            j2 = j1 + m;
            j3 = j2 + m;
            x0r = a[j] + a[j2];
            x0i = a[j + 1] + a[j2 + 1];
            x1r = a[j] - a[j2];
            x1i = a[j + 1] - a[j2 + 1];
            float y0r = a[j + 2] + a[j2 + 2];
            float y0i = a[j + 3] + a[j2 + 3];
            float y1r = a[j + 2] - a[j2 + 2];
            float y1i = a[j + 3] - a[j2 + 3];
            x2r = a[j1] + a[j3];
            x2i = a[j1 + 1] + a[j3 + 1];
            x3r = a[j1] - a[j3];
            x3i = a[j1 + 1] - a[j3 + 1];
            float y2r = a[j1 + 2] + a[j3 + 2];
            float y2i = a[j1 + 3] + a[j3 + 3];
            float y3r = a[j1 + 2] - a[j3 + 2];
            float y3i = a[j1 + 3] - a[j3 + 3];
            a[j] = x0r + x2r;
            a[j + 1] = x0i + x2i;
            a[j + 2] = y0r + y2r;
            a[j + 3] = y0i + y2i;
            a[j1] = x0r - x2r;
            a[j1 + 1] = x0i - x2i;
            a[j1 + 2] = y0r - y2r;
            a[j1 + 3] = y0i - y2i;
            x0r = x1r - x3i;
            x0i = x1i + x3r;
            a[j2] = Fms(wk1r, x0r, wk1i * x0i);
            a[j2 + 1] = Fma(wk1r, x0i, wk1i * x0r);
            x0r = y1r - y3i;
            x0i = y1i + y3r;
            a[j2 + 2] = Fms(wd1r, x0r, wd1i * x0i);
            a[j2 + 3] = Fma(wd1r, x0i, wd1i * x0r);
            x0r = x1r + x3i;
            x0i = x1i - x3r;
            a[j3] = Fma(wk3r, x0r, wk3i * x0i);
            a[j3 + 1] = Fms(wk3r, x0i, wk3i * x0r);
            x0r = y1r + y3i;
            x0i = y1i - y3r;
            a[j3 + 2] = Fma(wd3r, x0r, wd3i * x0i);
            a[j3 + 3] = Fms(wd3r, x0i, wd3i * x0r);
            int j0 = m - j;
            j1 = j0 + m;
            j2 = j1 + m;
            j3 = j2 + m;
            x0r = a[j0] + a[j2];
            x0i = a[j0 + 1] + a[j2 + 1];
            x1r = a[j0] - a[j2];
            x1i = a[j0 + 1] - a[j2 + 1];
            y0r = a[j0 - 2] + a[j2 - 2];
            y0i = a[j0 - 1] + a[j2 - 1];
            y1r = a[j0 - 2] - a[j2 - 2];
            y1i = a[j0 - 1] - a[j2 - 1];
            x2r = a[j1] + a[j3];
            x2i = a[j1 + 1] + a[j3 + 1];
            x3r = a[j1] - a[j3];
            x3i = a[j1 + 1] - a[j3 + 1];
            y2r = a[j1 - 2] + a[j3 - 2];
            y2i = a[j1 - 1] + a[j3 - 1];
            y3r = a[j1 - 2] - a[j3 - 2];
            y3i = a[j1 - 1] - a[j3 - 1];
            a[j0] = x0r + x2r;
            a[j0 + 1] = x0i + x2i;
            a[j0 - 2] = y0r + y2r;
            a[j0 - 1] = y0i + y2i;
            a[j1] = x0r - x2r;
            a[j1 + 1] = x0i - x2i;
            a[j1 - 2] = y0r - y2r;
            a[j1 - 1] = y0i - y2i;
            x0r = x1r - x3i;
            x0i = x1i + x3r;
            a[j2] = Fms(wk1i, x0r, wk1r * x0i);
            a[j2 + 1] = Fma(wk1i, x0i, wk1r * x0r);
            x0r = y1r - y3i;
            x0i = y1i + y3r;
            a[j2 - 2] = Fms(wd1i, x0r, wd1r * x0i);
            a[j2 - 1] = Fma(wd1i, x0i, wd1r * x0r);
            x0r = x1r + x3i;
            x0i = x1i - x3r;
            a[j3] = Fma(wk3i, x0r, wk3r * x0i);
            a[j3 + 1] = Fms(wk3i, x0i, wk3r * x0r);
            x0r = y1r + y3i;
            x0i = y1i - y3r;
            a[j3 - 2] = Fma(wd3i, x0r, wd3r * x0i);
            a[j3 - 1] = Fms(wd3i, x0i, wd3r * x0r);
        }
        wk1r = csc1 * (wd1r + wn4r);
        wk1i = csc1 * (wd1i + wn4r);
        wk3r = csc3 * (wd3r - wn4r);
        wk3i = csc3 * (wd3i - wn4r);
        int c0 = mh;
        j1 = c0 + m;
        j2 = j1 + m;
        j3 = j2 + m;
        x0r = a[c0 - 2] + a[j2 - 2];
        x0i = a[c0 - 1] + a[j2 - 1];
        x1r = a[c0 - 2] - a[j2 - 2];
        x1i = a[c0 - 1] - a[j2 - 1];
        x2r = a[j1 - 2] + a[j3 - 2];
        x2i = a[j1 - 1] + a[j3 - 1];
        x3r = a[j1 - 2] - a[j3 - 2];
        x3i = a[j1 - 1] - a[j3 - 1];
        a[c0 - 2] = x0r + x2r;
        a[c0 - 1] = x0i + x2i;
        a[j1 - 2] = x0r - x2r;
        a[j1 - 1] = x0i - x2i;
        x0r = x1r - x3i;
        x0i = x1i + x3r;
        a[j2 - 2] = Fms(wk1r, x0r, wk1i * x0i);
        a[j2 - 1] = Fma(wk1r, x0i, wk1i * x0r);
        x0r = x1r + x3i;
        x0i = x1i - x3r;
        a[j3 - 2] = Fma(wk3r, x0r, wk3i * x0i);
        a[j3 - 1] = Fms(wk3r, x0i, wk3i * x0r);
        x0r = a[c0] + a[j2];
        x0i = a[c0 + 1] + a[j2 + 1];
        x1r = a[c0] - a[j2];
        x1i = a[c0 + 1] - a[j2 + 1];
        x2r = a[j1] + a[j3];
        x2i = a[j1 + 1] + a[j3 + 1];
        x3r = a[j1] - a[j3];
        x3i = a[j1 + 1] - a[j3 + 1];
        a[c0] = x0r + x2r;
        a[c0 + 1] = x0i + x2i;
        a[j1] = x0r - x2r;
        a[j1 + 1] = x0i - x2i;
        x0r = x1r - x3i;
        x0i = x1i + x3r;
        a[j2] = wn4r * (x0r - x0i);
        a[j2 + 1] = wn4r * (x0i + x0r);
        x0r = x1r + x3i;
        x0i = x1i - x3r;
        a[j3] = -wn4r * (x0r + x0i);
        a[j3 + 1] = -wn4r * (x0i - x0r);
        x0r = a[c0 + 2] + a[j2 + 2];
        x0i = a[c0 + 3] + a[j2 + 3];
        x1r = a[c0 + 2] - a[j2 + 2];
        x1i = a[c0 + 3] - a[j2 + 3];
        x2r = a[j1 + 2] + a[j3 + 2];
        x2i = a[j1 + 3] + a[j3 + 3];
        x3r = a[j1 + 2] - a[j3 + 2];
        x3i = a[j1 + 3] - a[j3 + 3];
        a[c0 + 2] = x0r + x2r;
        a[c0 + 3] = x0i + x2i;
        a[j1 + 2] = x0r - x2r;
        a[j1 + 3] = x0i - x2i;
        x0r = x1r - x3i;
        x0i = x1i + x3r;
        a[j2 + 2] = Fms(wk1i, x0r, wk1r * x0i);
        a[j2 + 3] = Fma(wk1i, x0i, wk1r * x0r);
        x0r = x1r + x3i;
        x0i = x1i - x3r;
        a[j3 + 2] = Fma(wk3i, x0r, wk3r * x0i);
        a[j3 + 3] = Fms(wk3i, x0i, wk3r * x0r);
    }

    private static void CftMdl1(int n, Span<float> a, ReadOnlySpan<float> w)
    {
        int mh = n >> 3;
        int m = 2 * mh;
        int j1 = m;
        int j2 = j1 + m;
        int j3 = j2 + m;
        float x0r = a[0] + a[j2];
        float x0i = a[1] + a[j2 + 1];
        float x1r = a[0] - a[j2];
        float x1i = a[1] - a[j2 + 1];
        float x2r = a[j1] + a[j3];
        float x2i = a[j1 + 1] + a[j3 + 1];
        float x3r = a[j1] - a[j3];
        float x3i = a[j1 + 1] - a[j3 + 1];
        a[0] = x0r + x2r;
        a[1] = x0i + x2i;
        a[j1] = x0r - x2r;
        a[j1 + 1] = x0i - x2i;
        a[j2] = x1r - x3i;
        a[j2 + 1] = x1i + x3r;
        a[j3] = x1r + x3i;
        a[j3 + 1] = x1i - x3r;
        float wn4r = w[1];
        int k = 0;
        for (int j = 2; j < mh; j += 2)
        {
            k += 4;
            float wk1r = w[k];
            float wk1i = w[k + 1];
            float wk3r = w[k + 2];
            float wk3i = -w[k + 3];
            j1 = j + m;
            j2 = j1 + m;
            j3 = j2 + m;
            x0r = a[j] + a[j2];
            x0i = a[j + 1] + a[j2 + 1];
            x1r = a[j] - a[j2];
            x1i = a[j + 1] - a[j2 + 1];
            x2r = a[j1] + a[j3];
            x2i = a[j1 + 1] + a[j3 + 1];
            x3r = a[j1] - a[j3];
            x3i = a[j1 + 1] - a[j3 + 1];
            a[j] = x0r + x2r;
            a[j + 1] = x0i + x2i;
            a[j1] = x0r - x2r;
            a[j1 + 1] = x0i - x2i;
            x0r = x1r - x3i;
            x0i = x1i + x3r;
            a[j2] = Fms(wk1r, x0r, wk1i * x0i);
            a[j2 + 1] = Fma(wk1r, x0i, wk1i * x0r);
            x0r = x1r + x3i;
            x0i = x1i - x3r;
            a[j3] = Fma(wk3r, x0r, wk3i * x0i);
            a[j3 + 1] = Fms(wk3r, x0i, wk3i * x0r);
            int j0 = m - j;
            j1 = j0 + m;
            j2 = j1 + m;
            j3 = j2 + m;
            x0r = a[j0] + a[j2];
            x0i = a[j0 + 1] + a[j2 + 1];
            x1r = a[j0] - a[j2];
            x1i = a[j0 + 1] - a[j2 + 1];
            x2r = a[j1] + a[j3];
            x2i = a[j1 + 1] + a[j3 + 1];
            x3r = a[j1] - a[j3];
            x3i = a[j1 + 1] - a[j3 + 1];
            a[j0] = x0r + x2r;
            a[j0 + 1] = x0i + x2i;
            a[j1] = x0r - x2r;
            a[j1 + 1] = x0i - x2i;
            x0r = x1r - x3i;
            x0i = x1i + x3r;
            a[j2] = Fms(wk1i, x0r, wk1r * x0i);
            a[j2 + 1] = Fma(wk1i, x0i, wk1r * x0r);
            x0r = x1r + x3i;
            x0i = x1i - x3r;
            a[j3] = Fma(wk3i, x0r, wk3r * x0i);
            a[j3 + 1] = Fms(wk3i, x0i, wk3r * x0r);
        }
        int c0 = mh;
        j1 = c0 + m;
        j2 = j1 + m;
        j3 = j2 + m;
        x0r = a[c0] + a[j2];
        x0i = a[c0 + 1] + a[j2 + 1];
        x1r = a[c0] - a[j2];
        x1i = a[c0 + 1] - a[j2 + 1];
        x2r = a[j1] + a[j3];
        x2i = a[j1 + 1] + a[j3 + 1];
        x3r = a[j1] - a[j3];
        x3i = a[j1 + 1] - a[j3 + 1];
        a[c0] = x0r + x2r;
        a[c0 + 1] = x0i + x2i;
        a[j1] = x0r - x2r;
        a[j1 + 1] = x0i - x2i;
        x0r = x1r - x3i;
        x0i = x1i + x3r;
        a[j2] = wn4r * (x0r - x0i);
        a[j2 + 1] = wn4r * (x0i + x0r);
        x0r = x1r + x3i;
        x0i = x1i - x3r;
        a[j3] = -wn4r * (x0r + x0i);
        a[j3 + 1] = -wn4r * (x0i - x0r);
    }

    private static void CftMdl2(int n, Span<float> a, ReadOnlySpan<float> w)
    {
        int mh = n >> 3;
        int m = 2 * mh;
        float wn4r = w[1];
        int j1 = m;
        int j2 = j1 + m;
        int j3 = j2 + m;
